#
# - compact medieval courser silhouette
# - narrower horse-like rib cage
# - high withers
# - curved belly and flank
# - smaller smoother neck
# - substantial cheek / small muzzle
# - legs underneath body instead of outside it
# - readable stifle / gaskin / hock
# - much cleaner tail
# ============================================================


